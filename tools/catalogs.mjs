import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";
export const hash = (value) => createHash("sha256").update(value).digest("hex");
export function manifest(root) {
  return JSON.parse(fs.readFileSync(path.join(root, "architecture/modules.json"), "utf8"));
}
export function readCatalog(root, file) {
  const source = ts.createSourceFile(
    file,
    fs.readFileSync(path.join(root, file), "utf8"),
    ts.ScriptTarget.Latest,
    true,
  );
  if (source.statements.length !== 1 || !ts.isVariableStatement(source.statements[0]))
    throw new Error(`sql-static: ${file}: only a named static catalog is allowed`);
  const statement = source.statements[0];
  const declaration = statement.declarationList.declarations[0];
  if (
    statement.declarationList.declarations.length !== 1 ||
    declaration.name.getText(source) !== "queries" ||
    !(statement.declarationList.flags & ts.NodeFlags.Const)
  )
    throw new Error(`sql-static: ${file}: expected const queries`);
  let object = declaration.initializer;
  if (ts.isAsExpression(object) && object.type.getText(source) === "const")
    object = object.expression;
  if (!ts.isObjectLiteralExpression(object))
    throw new Error(`sql-static: ${file}: expected literal object`);
  const queries = {};
  for (const property of object.properties) {
    if (
      !ts.isPropertyAssignment(property) ||
      !(ts.isIdentifier(property.name) || ts.isStringLiteral(property.name)) ||
      !(
        ts.isStringLiteral(property.initializer) ||
        ts.isNoSubstitutionTemplateLiteral(property.initializer)
      )
    )
      throw new Error(`sql-static: ${file}: dynamic SQL or identifier`);
    const key = property.name.text;
    if (Object.hasOwn(queries, key) || ["__proto__", "constructor", "prototype"].includes(key))
      throw new Error(`sql-static: ${file}: duplicate/reserved query name`);
    queries[key] = property.initializer.text;
  }
  return queries;
}
export function collect(root) {
  const result = {};
  for (const owner of manifest(root).owners.filter((owner) => owner.storage)) {
    const storage = owner.storage;
    const migrations = fs
      .readdirSync(path.join(root, storage.migrations))
      .filter((name) => name.endsWith(".sql"))
      .sort()
      .map((version) => {
        const sql = fs.readFileSync(path.join(root, storage.migrations, version), "utf8");
        return { version, checksum: hash(sql), sql };
      });
    result[owner.id] = { ...storage, queries: readCatalog(root, storage.catalog), migrations };
  }
  return result;
}
export function sqlCheck(root, data = collect(root)) {
  const result = spawnSync("python3", [new URL("./sql_check.py", import.meta.url).pathname], {
    input: JSON.stringify(data),
    encoding: "utf8",
  });
  if (result.status !== 0) throw new Error(result.stderr || result.stdout || String(result.error));
  return JSON.parse(result.stdout);
}
export function generated(root) {
  const data = collect(root);
  const checked = sqlCheck(root, data);
  const catalogHash = hash(JSON.stringify(data));
  return `// Generated by pnpm generate. Do not edit.\nexport const catalogHash = ${JSON.stringify(catalogHash)};\nexport const catalogs = ${JSON.stringify(checked, null, 2)} as const;\n`;
}
